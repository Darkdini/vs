function battleHelpWin() {
  const tabs = `<div class="coin-tabs bh4">${Object.entries(BH).map(([k, [t]]) => `<button class="${S.bhTab === k ? 'on' : ''}" data-bhtab="${k}">${t}</button>`).join('')}</div>`;
  return `${ribbon('Боевая система')}${tabs}<div class="pstats bhelp">${(BH[S.bhTab] || BH.stats)[1]()}</div>`;
}
$('#sheetBody').addEventListener('click', (e) => {
  if (e.target.closest('[data-rsvhelp]')) return openSheet(reserveHelpWin);
  const t = e.target.closest('[data-bhelp],[data-bhtab]'); if (!t) return;
  if (t.dataset.bhtab) { S.bhTab = t.dataset.bhtab; return refreshSheet(); }
  S.bhTab = 'stats'; openSheet(battleHelpWin);
});
