'use strict';
// Фильтр мата в общем чате (social.js chatPost): слово с матом заменяется на «***» — у всех, и у автора. Без наказаний:
// нарушителей по-прежнему предупреждают и банят модераторы (chatmod.js).
// Ловит и хитрые написания: латинские буквы-двойники (xyй), цифры вместо букв (6лядь), точки и дефисы внутри слова (х.у.й),
// растянутые буквы (бляяять), слово по буквам через пробел (б л я т ь), русский мат латиницей (blyat) и английский.
// Не трогает обычные слова, похожие на мат: корабля, употреблять, хлеб, небо, застрахуй, психую, команда, педикюр, бляха.

// латинские буквы и цифры, похожие на русские: в слове с русскими буквами читаются как русские
// (u — то «и», то «у»: проверяются оба прочтения)
const LOOK = { a: 'а', b: 'б', c: 'с', e: 'е', h: 'н', i: 'и', k: 'к', m: 'м', n: 'п', o: 'о', p: 'р', r: 'г', t: 'т', x: 'х', y: 'у', 0: 'о', 3: 'з', 4: 'ч', 6: 'б', '@': 'а', $: 'с', 'і': 'и', 'ё': 'е' };
// цифры и знаки вместо латинских букв: f4ck, sh1t
const LEET = { 0: 'o', 1: 'i', 3: 'e', 4: 'a', 5: 's', 7: 't', '@': 'a', $: 's' };
// корни: русские — в слове с русскими буквами, латинские — в слове целиком латиницей
const RU = [
  /(?<!стра|пси)ху[йиеюя]/u, /^ху(?:ли|ль)$/u, // хуй, хуе, хуя, хую, хуи, хули (но не «страхуй», «психую», «хулиган»)
  /п[иеы][зс]д/u, // пизд-, пезд-, писд-
  /^(?:за|по|на|вы|у|до|про|пере|недо|от[ъь]?|раз[ъь]?|рас|под[ъь]|с[ъь]|в[ъь]|вз[ъь]|об[ъь]|из[ъь]|долб[оа]|мозго)?еб(?!ург)/u, // еб-, заеб-, отъеб-, долбоеб (но не «небо», «хлеб», «себя»)
  /^бля(?!х)/u, /бляд/u, // бля, блять, блядь, выблядок (но не «корабля», «употреблять», «бляха»)
  /^сук(?:а|и|е|у|ой|ин|ина|ины|ину)$/u, /^суч(?:ка|ки|ке|ку|кой|ара|ары|ий|ья|ье|ьи|ьей)$/u, // сука, сучка (но не «сукно»)
  /муд(?:а[кч]|ил|оз)/u, /пид[оа]р|пидр|педераст|педик(?!ю)/u, /залуп/u, /г[оа]ндон/u, /шлюх/u, /^манд(?:а|ы|у|ой|е)$|мандав/u, /дроч/u,
];
const EN = [
  /hu[yij]|xu[yij]|xy[yuij]|hue[sv]/, /pi[zs]d|pezd/, /^bl[yj]a(?!h)|bl[yj]ad/, /^(?:suka|suki|cyka|cyki)$/, /^(?:za|po|na|vy|u|do|pro|ot|raz|pod)?y?eba[lnt]|zaeb|uebo?k/,
  /pid[oa]r|pidr/, /mudak|mudil/, /g[ao]ndon/, /zalup/, /shl[yj]uh/,
  /fuc?k|fck|phuck|fvck/, /shit/, /bitch|biatch/, /cunt/, /asshole/, /faggot/, /motherf/,
];
const SEP = /[.\-_'`|]/gu;
const squeeze = (s) => s.replace(/(.)\1+/gu, '$1'); // растянутые буквы: бляяять → блять
// есть ли мат в слове (как написано: регистр, двойники, точки внутри)
function isMat(word) {
  const w = word.toLowerCase().replace(SEP, '');
  if (!w) return false;
  if (/[а-яёі]/u.test(w)) {
    const look = (u) => squeeze([...w].map((ch) => (ch === 'u' ? u : LOOK[ch] || ch)).join(''));
    return [look('и'), look('у')].some((v) => RU.some((re) => re.test(v)));
  }
  if (!/^[a-z0-9@$]+$/.test(w)) return false;
  const v = squeeze([...w].map((ch) => LEET[ch] || ch).join(''));
  return EN.some((re) => re.test(v));
}
// слово: буквы и цифры, внутри — точки, дефисы, подчёркивания (х.у.й — одно слово)
const WORD = /[\p{L}\p{N}@$]+(?:[.\-_'`|]+[\p{L}\p{N}@$]+)*/gu;
// текст с матом, заменённым на «***»
function censorMat(text) {
  text = String(text || '');
  const words = [...text.matchAll(WORD)].map((m) => ({ s: m.index, e: m.index + m[0].length, w: m[0] }));
  const cut = []; // [начало, конец) кусков, которые станут «***»
  for (let i = 0; i < words.length; i++) {
    // слово по буквам: «б л я т ь», «х*у*й» — подряд однобуквенные, между ними только пробелы и знаки
    let j = i; while (j + 1 < words.length && [...words[j].w].length === 1 && [...words[j + 1].w].length === 1 && /^[\s.\-_*'`|]+$/u.test(text.slice(words[j].e, words[j + 1].s))) j++;
    if (j > i && isMat(words.slice(i, j + 1).map((x) => x.w).join(''))) { cut.push([words[i].s, words[j].e]); i = j; continue; }
    if (isMat(words[i].w)) cut.push([words[i].s, words[i].e]);
  }
  let out = text;
  for (const [s, e] of cut.reverse()) out = `${out.slice(0, s)}***${out.slice(e)}`;
  return out;
}

module.exports = { censorMat, isMat };
