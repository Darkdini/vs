// Какую картинку показывать для уровня (земли «растут»: маленькое → среднее → большое здание)
function displayId(b, level) {
  if (!b.tiers) return b.id;
  return level >= 10 ? b.tiers[2] : level >= 5 ? b.tiers[1] : b.tiers[0];
}

